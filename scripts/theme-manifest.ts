// Writes src/theme/package-themes.ts: every themes/**/*.theme.json as a static import, so a bundler (Vercel)
// ships them with the server. Run after adding, renaming or removing a theme file:  npx tsx scripts/theme-manifest.ts
// (test/core.test.ts fails when the list and the files on disk disagree).
import fs from 'node:fs';
import path from 'node:path';
import { ROOT } from '../src/config.js';

export function themeFiles(): string[] {
  const walk = (d: string): string[] => fs.readdirSync(d, { withFileTypes: true }).flatMap((e) => {
    const p = path.join(d, e.name);
    return e.isDirectory() ? walk(p) : e.name.endsWith('.theme.json') ? [path.relative(ROOT, p).split(path.sep).join('/')] : [];
  });
  return walk(path.join(ROOT, 'themes')).sort();
}

if (process.argv[1] && path.resolve(process.argv[1]).endsWith(path.join('scripts', 'theme-manifest.ts'))) {
  const files = themeFiles();
  const out = [
    '// Generated by scripts/theme-manifest.ts. Do not edit; re-run the script after changing themes/.',
    '// Static imports so bundlers (Vercel) include every package theme with the server.',
    ...files.map((f, i) => `import t${i} from '../../${f}' with { type: 'json' };`),
    '',
    'export const PACKAGE_THEMES: { file: string; raw: unknown }[] = [',
    ...files.map((f, i) => `  { file: '${f}', raw: t${i} },`),
    '];',
    '',
  ].join('\n');
  fs.writeFileSync(path.join(ROOT, 'src', 'theme', 'package-themes.ts'), out);
  console.log(`wrote src/theme/package-themes.ts (${files.length} themes)`);
}
